const extras = new Map<string, Place>()

export function getPlace(id: string) {
  return extras.get(id) ?? PLACES.find((p) => p.id === id)
}

export function registerPlaces(list: Place[]) {
  for (const p of list) extras.set(p.id, p)
}

export function registeredPlaces() {
  return [...extras.values()]
}

export function placesForDestination(destinationId: string) {
  const extra = [...extras.values()].filter((p) => p.destinationId === destinationId)
  const catalog = PLACES.filter((p) => p.destinationId === destinationId)
  const ids = new Set(extra.map((p) => p.id))
  return [...extra, ...catalog.filter((p) => !ids.has(p.id))]
}

